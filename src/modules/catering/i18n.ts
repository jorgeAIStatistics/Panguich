const dict: Record<Locale, Dict> = { en, es };

export type CateringDict = Dict;

export function cateringDict(locale: Locale): CateringDict {
  return dict[locale];
}

/** The words for an error code. Unknown codes (for example from an old link) get a generic line. */
export function cateringErrorText(t: CateringDict, code: string | undefined): string | null {
  if (!code) return null;
  return code in t.errors ? t.errors[code as ErrorKey] : t.errors.unknown;
}

export function blockText(t: CateringDict, block: TransitionBlock, eventDateLabel: string): string {
  return block === "event_not_yet" ? t.stage.blocks.event_not_yet(eventDateLabel) : t.stage.blocks[block];
}
